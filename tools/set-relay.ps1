# Încorporează adresa și cheia relay-ului în aplicație (la următoarea compilare).
# Generează src/KodDesk.Core/RelayConfig.Local.cs, care este exclus din git.
#
#   .\tools\set-relay.ps1                 # cere adresa și cheia
#   .\tools\set-relay.ps1 -Clear          # elimină relay-ul încorporat (se va configura din Setări)
param(
    [string]$Address,
    [switch]$Clear
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$file = Join-Path $root 'src\KodDesk.Core\RelayConfig.Local.cs'

if ($Clear) {
    if (Test-Path $file) { Remove-Item $file }
    Write-Host 'Relay-ul încorporat a fost eliminat. Recompilați aplicația.'
    return
}

if (-not $Address) { $Address = Read-Host 'Adresa relay (ex. wss://kod-desk.exemplu.ro)' }
$secure = Read-Host 'Cheia relay (RELAY_KEY din .env de pe server)' -AsSecureString
$key = [Net.NetworkCredential]::new('', $secure).Password
if (-not $Address -or -not $key) { throw 'Adresa și cheia sunt obligatorii.' }

$rng = [Security.Cryptography.RandomNumberGenerator]::Create()
function Mask([string]$text) {
    $data = [Text.Encoding]::UTF8.GetBytes($text)
    $mask = [byte[]]::new($data.Length)
    $rng.GetBytes($mask)
    $masked = for ($i = 0; $i -lt $data.Length; $i++) { $data[$i] -bxor $mask[$i] }
    return "Reveal([$($masked -join ', ')], [$($mask -join ', ')])"
}

$content = @"
// <auto-generated> de tools/set-relay.ps1 — NU adăugați acest fișier în git. </auto-generated>
#nullable enable
namespace KodDesk.Core;

public static partial class RelayConfig
{
    static partial void LoadEmbedded(ref string? address, ref string? key)
    {
        address = $(Mask $Address);
        key = $(Mask $key);
    }
}
"@
[IO.File]::WriteAllText($file, $content, [Text.UTF8Encoding]::new($false))
Write-Host "Relay încorporat: $Address (cheia este mascată). Recompilați aplicația."
